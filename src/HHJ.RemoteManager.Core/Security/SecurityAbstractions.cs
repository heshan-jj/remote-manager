using HHJ.RemoteManager.Core.Devices;
using HHJ.RemoteManager.Core.Ssh;

namespace HHJ.RemoteManager.Core.Security;

/// <summary>Stores small secrets (e.g. key passphrases) in Windows Credential Manager.</summary>
public interface ICredentialStore
{
    void Write(string target, string userName, string secret);
    string? Read(string target);
    bool Delete(string target);
}

/// <summary>Encrypts data at rest for the current Windows user (DPAPI).</summary>
public interface ISecretProtector
{
    byte[] Protect(byte[] plaintext);
    byte[] Unprotect(byte[] ciphertext);
}

public enum SshKeyStorage
{
    /// <summary>Key generated by HHJ; private key stored DPAPI-encrypted in the app data folder.</summary>
    ManagedDpapi,
    /// <summary>Existing OpenSSH key file referenced in place; optional passphrase in Credential Manager.</summary>
    ExternalFile,
}

public sealed class SshKeyInfo
{
    public string Id { get; set; } = Guid.NewGuid().ToString("N");
    public string Name { get; set; } = "";
    public SshKeyStorage Storage { get; set; }
    public string Algorithm { get; set; } = "";
    /// <summary>Single-line OpenSSH public key ("ecdsa-sha2-nistp256 AAAA... comment").</summary>
    public string PublicKey { get; set; } = "";
    public string FingerprintSha256 { get; set; } = "";
    /// <summary>Path of the key file (DPAPI blob for managed keys, OpenSSH file for external keys).</summary>
    public string PrivateKeyPath { get; set; } = "";
    public bool HasPassphrase { get; set; }
    public DateTimeOffset CreatedUtc { get; set; } = DateTimeOffset.UtcNow;
}

public interface ISshKeyStore
{
    Task<IReadOnlyList<SshKeyInfo>> ListAsync(CancellationToken cancellationToken = default);
    Task<SshKeyInfo?> GetAsync(string id, CancellationToken cancellationToken = default);

    /// <summary>Generates a new key pair in-process; private key never leaves this machine.</summary>
    Task<SshKeyInfo> GenerateAsync(string name, CancellationToken cancellationToken = default);

    /// <summary>References an existing OpenSSH private key file. The passphrase (if any) goes to Credential Manager.</summary>
    Task<SshKeyInfo> ImportAsync(string name, string privateKeyPath, string? passphrase, CancellationToken cancellationToken = default);

    Task DeleteAsync(string id, CancellationToken cancellationToken = default);

    /// <summary>Loads the private key into memory for a connect attempt.</summary>
    Task<PrivateKeyMaterial> LoadPrivateKeyAsync(string id, CancellationToken cancellationToken = default);
}

public interface IDeviceRepository
{
    Task<IReadOnlyList<DeviceProfile>> LoadAsync(CancellationToken cancellationToken = default);
    Task SaveAsync(IEnumerable<DeviceProfile> devices, CancellationToken cancellationToken = default);
}
